import builtins
import importlib
import inspect
import json
import keyword
import os
import sys
from pathlib import Path

_UNSUPPORTED_PARAM_KINDS = {
    inspect.Parameter.POSITIONAL_ONLY,
    inspect.Parameter.VAR_POSITIONAL,
    inspect.Parameter.VAR_KEYWORD,
}

# Regeneration only deletes files starting with this exact line, so a
# user's own tests in the output directory are never touched.
_GENERATED_MARKER = "# generated by ai-tracer - regenerated each run, do not edit"


def _is_valid_import_name(part):
    # "class".isidentifier() is True but it's a keyword, so
    # "from class import add" is still a SyntaxError.
    return part.isidentifier() and not keyword.iskeyword(part)


def _contains_array(value):
    # Lists and tuples both trace as JSON arrays, so a recorded array is
    # ambiguous: rendering it as a list could turn a tuple into one and
    # fail the generated assertion. Skip anything containing an array.
    if isinstance(value, list):
        return True
    if isinstance(value, dict):
        return any(_contains_array(item) for item in value.values())
    return False


def _is_generated_file(path):
    # Only the first line is checked, so this stays cheap and can't be
    # fooled by the marker text appearing lower in an unrelated file.
    try:
        with path.open(encoding="utf-8") as fh:
            return fh.readline().rstrip("\n") == _GENERATED_MARKER
    except (OSError, UnicodeDecodeError):
        return False


def _would_clobber(path):
    return path.exists() and not _is_generated_file(path)


def _is_importable_package_dir(path):
    # Regular package (__init__.py) or namespace package (any .py file
    # directly inside, even without __init__.py).
    if (path / "__init__.py").is_file():
        return True
    return any(child.suffix == ".py" for child in path.iterdir())


def _local_module_names(target_dir):
    # "conftest" is excluded: it's pytest's own infrastructure, and evicting
    # it mid-collection would delete the conftest pytest is importing.
    names = set()
    for entry in Path(target_dir).iterdir():
        if entry.is_file() and entry.suffix == ".py":
            names.add(entry.stem)
        elif entry.is_dir() and _is_importable_package_dir(entry):
            names.add(entry.name)
    names.discard("conftest")
    return names


def generate(trace_log_path, target_dir, output_dir="generated_tests"):
    calls = json.loads(Path(trace_log_path).read_text())
    target_dir = str(Path(target_dir).resolve())
    # Resolved before importing target code: a module that chdir()s at
    # import time would otherwise send a relative output_dir there instead.
    output_path = Path(output_dir).resolve()

    calls_by_module = {}
    module_cache = {}
    signature_cache = {}

    # Snapshot sys.path/sys.modules/cwd so anything target imports change
    # (sys.path entries, os.chdir(), cached modules) is undone afterward,
    # keeping repeated generate() calls in one process hermetic.
    original_sys_path = list(sys.path)
    original_sys_modules = dict(sys.modules)
    original_cwd = os.getcwd()
    sys.path.insert(0, target_dir)
    # Evict every name the target dir defines (not just the module under
    # test) so a same-named stale/stdlib module never wins, and evict any
    # cached submodule of a local package so it's re-imported fresh too.
    local_names = _local_module_names(target_dir)
    for name in list(sys.modules):
        if name.split(".")[0] in local_names:
            sys.modules.pop(name, None)
    try:
        for call in calls:
            reason = _skip_reason(call, module_cache, signature_cache)
            if reason is None:
                calls_by_module.setdefault(call["module"], []).append(call)
            else:
                print(
                    f"Skipping {call['module']}.{call['qualname']}: {reason}",
                    file=sys.stderr,
                )
    finally:
        sys.path[:] = original_sys_path
        sys.modules.clear()
        sys.modules.update(original_sys_modules)
        os.chdir(original_cwd)

    output_path.mkdir(exist_ok=True, parents=True)

    # Clear previously generated tests first, so a module that's no longer
    # generatable doesn't leave a stale test_*.py for pytest to run. Only
    # files carrying our marker are removed.
    for existing in output_path.glob("test_*.py"):
        if _is_generated_file(existing):
            existing.unlink()

    # A single conftest.py does the import setup once for the whole session
    # (puts target_dir on sys.path, evicts stale/shadowing modules), so a
    # shared package is only imported once across every generated test file.
    conftest_path = output_path / "conftest.py"
    if _would_clobber(conftest_path):
        print(
            f"Not writing {conftest_path}: a conftest.py that ai-tracer didn't "
            "generate is already there. The generated tests still import the "
            "target via their own sys.path setup, but the one-time eviction of "
            "stale/shadowing same-named modules is skipped, so if this pytest "
            "session already cached a module sharing a top-level name with the "
            "target, imports could resolve to it. Use an empty output directory "
            "(the default generated_tests/) to get the full setup.",
            file=sys.stderr,
        )
    else:
        conftest_path.write_text(_render_conftest(target_dir))

    # Numeric suffix avoids two clashes: module names flattening to the same
    # file ("pkg.sub" vs "pkg_sub"), and an existing unmarked file we
    # mustn't clobber.
    used_names = {}
    written_paths = []
    for module_name in sorted(calls_by_module):
        base = f"test_{module_name.replace('.', '_')}"
        file_name = f"{base}.py"
        suffix = 1
        while file_name in used_names or _would_clobber(output_path / file_name):
            file_name = f"{base}_{suffix}.py"
            suffix += 1
        used_names[file_name] = module_name
        test_path = output_path / file_name
        test_path.write_text(
            _render_test_module(module_name, calls_by_module[module_name], target_dir)
        )
        written_paths.append(test_path)

    return written_paths


def _skip_reason(call, module_cache, signature_cache):
    # None if the call can be generated, else a reason printed to stderr.
    if not call["qualname"].isidentifier():
        return "not a plain top-level function (method, nested function, or lambda)"
    # "__main__" always names the entry script, but this process can't
    # re-import that to mean "the traced script" - needs its real file path.
    if call["module"] == "__main__":
        return "the entry script's own functions aren't generatable yet (module \"__main__\" has no real import path)"
    # A target can rebind __name__ to a non-string; guard before treating
    # module as a dotted string.
    if not isinstance(call["module"], str) or not all(
        _is_valid_import_name(part) for part in call["module"].split(".")
    ):
        return f"module {call['module']!r} is not a valid import target"
    # An unjoined worker thread's call can be written before its return
    # event fires, with no raised/return_* fields.
    if "raised" not in call:
        return (
            "call didn't finish before tracing stopped (e.g. an unjoined worker thread)"
        )
    if any(kind != "json" for kind in call["arg_serialization"].values()):
        return "one or more arguments could not be captured as a JSON value"
    if any(_contains_array(value) for value in call["args"].values()):
        return "an argument contains a list/array (a tuple can't be told apart from a list in the trace yet)"
    if not call["raised"]:
        if call["return_serialization"] == "repr":
            return "return value could not be captured as a JSON value"
        if _contains_array(call["return_value"]):
            return "return value contains a list/array (a tuple can't be told apart from a list in the trace yet)"
    # Checked before the exception's own module: if the two are involved in
    # a circular import, importing the function's module first can succeed
    # where importing the exception module cold would fail.
    if _get_module(call["module"], module_cache) is None:
        return (
            f"module {call['module']!r} could not be imported (it may raise on import)"
        )
    if call["raised"]:
        exception_reason = _exception_skip_reason(call, module_cache)
        if exception_reason is not None:
            return exception_reason
    signature = _get_signature(
        call["module"], call["qualname"], module_cache, signature_cache
    )
    if signature is None:
        return (
            "function no longer exists, or can't be replayed as a plain "
            "synchronous call (async, generator, positional-only, *args, or "
            "**kwargs)"
        )
    # A supported signature may still have been renamed/changed since tracing.
    try:
        signature.bind(**dict.fromkeys(call["args"]))
    except TypeError:
        return "recorded arguments no longer match the function's signature"
    return None


def _exception_skip_reason(call, module_cache):
    # None if the exception can be named in a `pytest.raises(...)`, else a
    # skip reason.
    exception_type = call["exception_type"]
    exception_module = call["exception_module"]
    if not isinstance(exception_type, str) or not _is_valid_import_name(exception_type):
        return f"exception type {exception_type!r} is not a plain identifier"
    if exception_module == "builtins":
        if not hasattr(builtins, exception_type):
            return f"exception {exception_type!r} is not a builtin"
        return None
    # Same limits as a function's own module (see _skip_reason above).
    if not isinstance(exception_module, str) or exception_module == "__main__":
        return (
            f"exception module {exception_module!r} can't be imported "
            "(the entry script has no real import path, or it isn't a module name)"
        )
    if not all(_is_valid_import_name(part) for part in exception_module.split(".")):
        return f"exception module {exception_module!r} is not a valid import target"
    module = _get_module(exception_module, module_cache)
    if module is None or not hasattr(module, exception_type):
        return f"exception {exception_module}.{exception_type} could not be imported"
    return None


def _get_module(module_name, module_cache):
    # Cached per generate() call so a module referenced by many calls is
    # only imported (and its top-level code only re-run) once.
    if module_name not in module_cache:
        try:
            module_cache[module_name] = importlib.import_module(module_name)
        except KeyboardInterrupt:
            raise
        except BaseException:  # noqa: BLE001 - target import can raise anything
            # Not just Exception - SystemExit/GeneratorExit etc. all just
            # mean "not importable now", not "abort the whole run".
            module_cache[module_name] = None
    return module_cache[module_name]


def _get_signature(module_name, qualname, module_cache, signature_cache):
    # Current inspect.Signature for a generatable function, or None if it no
    # longer exists, can't be introspected, or uses an unreplayable
    # parameter kind. Cached by (module, qualname).
    key = (module_name, qualname)
    if key not in signature_cache:
        module = _get_module(module_name, module_cache)
        try:
            function = getattr(module, qualname)
            signature = inspect.signature(function)
        except KeyboardInterrupt:
            raise
        except BaseException:  # noqa: BLE001 - target hooks can raise anything
            # getattr/__getattr__ and inspect.signature/__signature__ are
            # target code and can raise anything; treat as not introspectable.
            signature_cache[key] = None
        else:
            # A coroutine/generator function returns that kind of object,
            # not the value the tracer recorded on await/resume.
            not_plainly_callable = (
                inspect.iscoroutinefunction(function)
                or inspect.isgeneratorfunction(function)
                or inspect.isasyncgenfunction(function)
            )
            has_unsupported_kind = any(
                p.kind in _UNSUPPORTED_PARAM_KINDS
                for p in signature.parameters.values()
            )
            signature_cache[key] = (
                None if not_plainly_callable or has_unsupported_kind else signature
            )
    return signature_cache[key]


def _render_conftest(target_dir):
    # Runs once per session, before any generated test file is collected:
    # puts target_dir on sys.path and evicts stale/shadowing target-local
    # modules, so a shared package is imported exactly once per session.
    local = sorted(_local_module_names(target_dir))
    lines = [
        _GENERATED_MARKER,
        "import sys",
        "",
        f"sys.path.insert(0, {target_dir!r})",
        "",
        "# Evict cached target-local modules/packages/submodules so tests",
        "# import fresh copies. Spare this conftest's own ancestor chain -",
        "# deleting it mid-import would abort collection with a KeyError.",
        f"_local = {tuple(local)!r}",
        "_keep = {__name__}",
        "_parent = __name__",
        "while '.' in _parent:",
        "    _parent = _parent.rsplit('.', 1)[0]",
        "    _keep.add(_parent)",
        "for _name in list(sys.modules):",
        "    if _name.split('.')[0] in _local and _name not in _keep:",
        "        del sys.modules[_name]",
    ]
    return "\n".join(lines) + "\n"


def _render_test_module(module_name, module_calls, target_dir):
    imported_names = sorted({call["qualname"] for call in module_calls})
    # Avoids colliding with a traced function named `result`, which would
    # otherwise turn `result = result(...)` into an UnboundLocalError.
    result_var = "result"
    while result_var in imported_names:
        result_var = "_" + result_var

    has_raises = any(call["raised"] for call in module_calls)
    has_builtin_raises = any(
        call["raised"] and call["exception_module"] == "builtins"
        for call in module_calls
    )
    # pytest/builtins/exception modules are imported under reserved aliases
    # (never a bare name), so a traced function named e.g. `pytest` or
    # `errors` can't shadow them.
    reserved = set(imported_names)

    def _reserve(base):
        alias = base
        while alias in reserved:
            alias = "_" + alias
        reserved.add(alias)
        return alias

    pytest_alias = _reserve("_raises_pytest") if has_raises else None
    builtins_alias = _reserve("_raises_builtins") if has_builtin_raises else None
    exception_modules = sorted(
        {
            call["exception_module"]
            for call in module_calls
            if call["raised"] and call["exception_module"] != "builtins"
        }
    )
    exception_aliases = {
        exception_module: _reserve("_raises_" + exception_module.replace(".", "_"))
        for exception_module in exception_modules
    }

    # This sys.path.insert is a fallback for when the generated conftest.py
    # was skipped or the file is run on its own.
    lines = [_GENERATED_MARKER, "import sys"]
    if has_raises:
        lines.append(f"import pytest as {pytest_alias}")
    if has_builtin_raises:
        lines.append(f"import builtins as {builtins_alias}")
    lines += ["", f"sys.path.insert(0, {target_dir!r})"]
    # Imported before any exception module - see the circular-import note
    # in _skip_reason above.
    lines.append(f"from {module_name} import {', '.join(imported_names)}")
    for exception_module in exception_modules:
        lines.append(
            f"import {exception_module} as {exception_aliases[exception_module]}"
        )

    call_counts = {}
    for call in module_calls:
        qualname = call["qualname"]
        index = call_counts.get(qualname, 0)
        call_counts[qualname] = index + 1

        args = ", ".join(f"{name}={value!r}" for name, value in call["args"].items())
        lines += ["", ""]
        lines.append(f"def test_{qualname}_{index}():")
        if call["raised"]:
            reference = _exception_reference(call, builtins_alias, exception_aliases)
            lines.append(f"    with {pytest_alias}.raises({reference}):")
            lines.append(f"        {qualname}({args})")
        else:
            lines.append(f"    {result_var} = {qualname}({args})")
            lines.append(f"    assert {result_var} == {call['return_value']!r}")

    return "\n".join(lines) + "\n"


def _exception_reference(call, builtins_alias, exception_aliases):
    if call["exception_module"] == "builtins":
        return f"{builtins_alias}.{call['exception_type']}"
    return f"{exception_aliases[call['exception_module']]}.{call['exception_type']}"


def main():
    argv = sys.argv[1:]
    if len(argv) not in (2, 3):
        print(
            "usage: python -m ai_tracer.generator <trace_log> <target_dir> [output_dir]",
            file=sys.stderr,
        )
        sys.exit(1)
    trace_log_path, target_dir, *rest = argv
    output_dir = rest[0] if rest else "generated_tests"
    for path in generate(trace_log_path, target_dir, output_dir):
        print(path)


if __name__ == "__main__":
    main()
